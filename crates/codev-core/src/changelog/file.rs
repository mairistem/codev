//! Where the generated text goes in `CHANGELOG.md`.
//!
//! The file is the team's: codev only owns a managed section, right after
//! the header, holding the `[Unreleased]` block. Released versions,
//! hand-written entries and the link references at the end are outside the
//! markers and stay byte for byte. One exception, on the first write only:
//! a hand-written `## [Unreleased]` heading is taken over by the managed
//! section, so the entries below it do not end up under a second
//! `[Unreleased]` heading.

use crate::managed;

/// The file `codev changelog --write` maintains, at the project root.
pub const FILE_NAME: &str = "CHANGELOG.md";

/// The opening line of the changelog's managed section.
pub const BEGIN_LINE: &str = "<!-- codev:begin — generated by `codev changelog --write` from the archived changes; edit outside this block -->";

/// The header of a `CHANGELOG.md` codev creates.
pub const DEFAULT_HEADER: &str = "# Changelog\n\nAll notable changes to this project are documented in this file.\n\nThe format is based on [Keep a Changelog](https://keepachangelog.com/en/1.1.0/).\n";

/// The heading every managed section starts with.
const UNRELEASED: &str = "## [Unreleased]";

/// Computes the new `CHANGELOG.md`.
///
/// - `unreleased`: the rendered `## [Unreleased]` block;
/// - `release`: the rendered `## [<version>] - <date>` block when
///   releasing — the managed section then only keeps an empty
///   `[Unreleased]`, and the version block follows it, outside the markers.
///
/// `Err` carries the reason when the markers are malformed; nothing must
/// be written then.
pub fn write(
    existing: Option<&str>,
    unreleased: &str,
    release: Option<&str>,
) -> Result<String, String> {
    let section = managed::render_section_with(
        BEGIN_LINE,
        if release.is_some() {
            UNRELEASED
        } else {
            unreleased
        },
    );
    let insertion = match release {
        Some(block) => format!("{section}\n{}\n", block.trim_end_matches('\n')),
        None => section,
    };

    let Some(text) = existing else {
        return Ok(format!("{DEFAULT_HEADER}\n{insertion}"));
    };
    if let Some(range) = managed::section_range(text)? {
        return Ok(format!(
            "{}{insertion}{}",
            &text[..range.start],
            &text[range.end..]
        ));
    }

    // No section yet: right after the header, i.e. before the first `## `.
    let mut offset = 0;
    for line in text.split_inclusive('\n') {
        let content = line.trim_end_matches(['\n', '\r']);
        if content.starts_with("## ") {
            let rest = &text[offset + line.len()..];
            return Ok(if content.trim_end().eq_ignore_ascii_case(UNRELEASED) {
                format!("{}{insertion}{rest}", &text[..offset])
            } else {
                format!("{}{insertion}\n{}", &text[..offset], &text[offset..])
            });
        }
        offset += line.len();
    }
    let mut contents = text.to_string();
    if !contents.is_empty() {
        if !contents.ends_with('\n') {
            contents.push('\n');
        }
        contents.push('\n');
    }
    contents.push_str(&insertion);
    Ok(contents)
}

/// The managed block of a `CHANGELOG.md`, line endings normalized and
/// surrounding blank lines trimmed — what doctor compares with a fresh
/// rendering. `None` without a well-formed section.
pub fn managed_block(text: &str) -> Option<String> {
    managed::section_body(text).map(|body| body.replace("\r\n", "\n").trim().to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    const UNRELEASED_BLOCK: &str = "## [Unreleased]\n\n### Added\n\n- a flag.\n";
    const RELEASE_BLOCK: &str = "## [1.1.0] - 2026-10-20\n\n### Added\n\n- a flag.\n";

    const HAND_WRITTEN: &str = "# Changelog\n\nIntro.\n\n## [Unreleased]\n\n### Changed\n\n- curated entry.\n\n## [1.0.0] - 2026-01-01\n\n### Added\n\n- first release.\n\n[Unreleased]: https://example.com/compare/v1.0.0...HEAD\n[1.0.0]: https://example.com/releases/tag/v1.0.0\n";

    #[test]
    fn write_creates_a_missing_file_with_a_header() {
        let contents = write(None, UNRELEASED_BLOCK, None).unwrap();
        assert!(contents.starts_with("# Changelog\n"));
        assert_eq!(managed_block(&contents).unwrap(), UNRELEASED_BLOCK.trim());
        assert!(contents.contains(&format!("\n\n{BEGIN_LINE}\n## [Unreleased]")));
    }

    #[test]
    fn write_adopts_a_hand_written_unreleased_heading() {
        let contents = write(Some(HAND_WRITTEN), UNRELEASED_BLOCK, None).unwrap();
        assert_eq!(contents.matches("## [Unreleased]").count(), 1);
        let expected = format!(
            "# Changelog\n\nIntro.\n\n{}\n### Changed\n\n- curated entry.\n\n## [1.0.0]",
            managed::render_section_with(BEGIN_LINE, UNRELEASED_BLOCK)
        );
        assert!(contents.starts_with(&expected), "{contents}");
    }

    #[test]
    fn write_keeps_released_sections_and_link_references() {
        let contents = write(Some(HAND_WRITTEN), UNRELEASED_BLOCK, None).unwrap();
        let released = &HAND_WRITTEN[HAND_WRITTEN.find("## [1.0.0]").unwrap()..];
        assert!(contents.ends_with(released));

        // Without a hand-written [Unreleased], the section goes before the
        // first version, separated by a blank line.
        let plain =
            HAND_WRITTEN.replace("## [Unreleased]\n\n### Changed\n\n- curated entry.\n\n", "");
        let contents = write(Some(&plain), UNRELEASED_BLOCK, None).unwrap();
        assert!(contents.contains(&format!(
            "{}\n## [1.0.0]",
            managed::END_LINE.to_owned() + "\n"
        )));
        assert!(contents.ends_with(&plain[plain.find("## [1.0.0]").unwrap()..]));
    }

    #[test]
    fn write_appends_to_a_file_without_any_version() {
        let contents = write(Some("# Changelog"), UNRELEASED_BLOCK, None).unwrap();
        assert!(contents.starts_with(&format!("# Changelog\n\n{BEGIN_LINE}")));
    }

    #[test]
    fn write_is_idempotent() {
        let once = write(Some(HAND_WRITTEN), UNRELEASED_BLOCK, None).unwrap();
        let twice = write(Some(&once), UNRELEASED_BLOCK, None).unwrap();
        assert_eq!(once, twice);
        let created = write(None, UNRELEASED_BLOCK, None).unwrap();
        assert_eq!(
            write(Some(&created), UNRELEASED_BLOCK, None).unwrap(),
            created
        );
    }

    #[test]
    fn release_rotates_the_managed_section() {
        let once = write(Some(HAND_WRITTEN), UNRELEASED_BLOCK, None).unwrap();
        let released = write(Some(&once), "## [Unreleased]\n", Some(RELEASE_BLOCK)).unwrap();
        assert_eq!(managed_block(&released).unwrap(), "## [Unreleased]");
        let expected = format!(
            "{}\n{RELEASE_BLOCK}\n### Changed\n\n- curated entry.\n\n## [1.0.0]",
            managed::render_section_with(BEGIN_LINE, "## [Unreleased]")
        );
        assert!(released.contains(&expected), "{released}");
        assert!(released.ends_with("[1.0.0]: https://example.com/releases/tag/v1.0.0\n"));
        // The next write refreshes the single managed section.
        let next = write(Some(&released), UNRELEASED_BLOCK, None).unwrap();
        assert_eq!(managed_block(&next).unwrap(), UNRELEASED_BLOCK.trim());
        assert!(next.contains(RELEASE_BLOCK));
    }

    #[test]
    fn write_refuses_malformed_markers() {
        let twice = format!(
            "# Changelog\n\n{}{}",
            managed::render_section_with(BEGIN_LINE, "a"),
            managed::render_section_with(BEGIN_LINE, "b")
        );
        assert!(write(Some(&twice), UNRELEASED_BLOCK, None).is_err());
        assert_eq!(managed_block(&twice), None);
    }
}

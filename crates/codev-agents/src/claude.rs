    fn isolated() -> RenderCtx {
        RenderCtx {
            review_mode: ReviewMode::Isolated,
            ..RenderCtx::default()
        }
    }

    fn tools_of(rendered: &str) -> Vec<String> {
        allowed_tools(rendered)
    }

    #[test]
    fn isolated_mode_adds_the_agent_tool_to_review_skills_only() {
        for workflow in workflows::CATALOG {
            let tools = tools_of(&ClaudeCode::render(workflow, VERSION, &isolated()));
            let reviews = matches!(workflow.id, "propose" | "apply");
            assert_eq!(
                tools.last().map(String::as_str) == Some(AGENT_TOOL),
                reviews,
                "{}: {tools:?}",
                workflow.id
            );
            assert!(
                tools.iter().filter(|t| *t == AGENT_TOOL).count() <= 1,
                "{tools:?}"
            );
        }
        // With a Jira tool, both are there, the sub-agent tool last.
        let ctx = RenderCtx {
            jira_mcp_tool: Some("mcp__x__getJiraIssue".into()),
            review_mode: ReviewMode::Isolated,
        };
        let tools = tools_of(&ClaudeCode::render(propose(), VERSION, &ctx));
        assert_eq!(
            &tools[tools.len() - 2..],
            ["mcp__x__getJiraIssue", AGENT_TOOL]
        );
    }

